# Division Operations

def decimal_division(x,y):
    if (y==0):
        return("Error,Division by zero is not allowed.")
    return(x/y)


def floor_division(x,y):
    if (y==0):
        return("Error,Division by zero is not allowed.")
    return(x//y)


def remainder(x,y):
    if (y==0):
        return("Error,Division by zero is not allowed.")
    return(x%y)

